function [r_meas, theta_meas, meas_valid, truth] = target_motion_generator(t, scenario, seed)
%TARGET_MOTION_GENERATOR  Simulated moving object and noisy polar sensor.
%
%   [r_meas, theta_meas, meas_valid] = target_motion_generator(t, scenario)
%   [..., truth] = target_motion_generator(t, scenario, seed)
%
%   Inputs
%     t         time [s] (any t in [0, t_end + 1]; sensor samples occur at
%               multiples of Ts_radar = 0.05 s)
%     scenario  'A' (nominal), 'B' (manoeuvring), 'C' (manoeuvring + sensor
%               loss), or a struct with the fields of P.scen.A (custom case)
%     seed      (optional) integer noise seed, default P.seed
%
%   Outputs
%     r_meas      last available measured range           [m]
%     theta_meas  last available measured elevation angle [rad]
%     meas_valid  true only at a sensor-sample instant at which a NEW
%                 measurement is available (false during measurement loss)
%     truth       struct with exact x, y, vx, vy, ax, ay, r, theta at time t
%                 (for evaluation only; never passed to the controller)
%
%   Geometry (2-D elevation plane): x = horizontal distance from the
%   platform, y = height above the platform, r = hypot(x,y),
%   theta = atan2(y,x).  Noise is zero-mean Gaussian with sigma_r and
%   sigma_theta from parameters.m, generated by a Park-Miller LCG +
%   Box-Muller so results are bit-reproducible in MATLAB and Octave.
%
%   The trajectory generator ENFORCES the range, speed and acceleration
%   limits of the assignment: it raises an error if any generated
%   trajectory violates them on [0, t_end + Tp].
%
%   Authors: Sayam Midha (24B2240), Piyush Meena (24B2275), Monaal Kumar Arya (24B2156), Asmit Anand (24B2263), Shivam Gawande (24B2194), ME319 Autumn 2026.

persistent Pc sig tg X Y VX VY AX AY rm thm valid hold Tgrid

if isempty(Pc), Pc = parameters(); end
if nargin < 3 || isempty(seed), seed = Pc.seed; end

% ---- resolve scenario ---------------------------------------------------
if ischar(scenario)
    key = upper(scenario);
    if ~isfield(Pc.scen, key)
        error('target_motion_generator:badScenario', ...
              'Unknown scenario "%s" (use A, B, C or a struct).', scenario);
    end
    cfg = Pc.scen.(key);
elseif isstruct(scenario)
    cfg = scenario;
else
    error('target_motion_generator:badScenario', 'scenario must be char or struct.');
end
if isnan(cfg.t_bo0), cfg.t_bo0 = Inf; end
newsig = [cfg.p0(:); cfg.v0(:); cfg.Ax; cfg.wx; cfg.phx; cfg.Ay; cfg.wy; cfg.phy; ...
          cfg.t_man; cfg.t_ramp; cfg.t_bo0; cfg.t_bo; seed];

% ---- (re)build trajectory + sensor record if the case changed -----------
if isempty(sig) || ~isequal(sig, newsig)
    sig = newsig;
    dtg   = 1e-3;                              % truth grid [s]
    Tgrid = Pc.t_end + Pc.Tp + 0.5;            % generated horizon [s]
    tg  = (0:round(Tgrid/dtg))' * dtg;
    tau = tg - cfg.t_man;
    u   = min(max(tau/cfg.t_ramp, 0), 1);
    wdw = u.^2 .* (3 - 2*u);                   % smoothstep window (C1)
    on  = double(tau >= 0);
    AX  = cfg.Ax * sin(cfg.wx*tau + cfg.phx) .* wdw .* on;
    AY  = cfg.Ay * sin(cfg.wy*tau + cfg.phy) .* wdw .* on;
    VX  = cfg.v0(1) + cumtrapz(tg, AX);
    VY  = cfg.v0(2) + cumtrapz(tg, AY);
    X   = cfg.p0(1) + cumtrapz(tg, VX);
    Y   = cfg.p0(2) + cumtrapz(tg, VY);

    % --- enforce assignment limits on [0, t_end + Tp] ---
    m  = tg <= Pc.t_end + Pc.Tp + 1e-9;
    rr = hypot(X(m), Y(m));
    if min(rr) < Pc.r_min || max(rr) > Pc.r_max
        error('target_motion_generator:rangeViolation', ...
              'Range limit violated: r in [%.1f, %.1f] m.', min(rr), max(rr));
    end
    if max(hypot(VX(m), VY(m))) > Pc.v_max
        error('target_motion_generator:speedViolation', 'Speed limit violated.');
    end
    if max(hypot(AX(m), AY(m))) > Pc.a_max
        error('target_motion_generator:accelViolation', 'Acceleration limit violated.');
    end

    % --- sensor record: noisy polar samples at multiples of Ts ---
    K   = floor(Tgrid/Pc.Ts_radar) + 1;
    ks  = round((0:K-1)' * Pc.Ts_radar / dtg) + 1;       % grid index of samples
    z   = gauss_lcg(2*K, seed);
    rm  = hypot(X(ks), Y(ks))   + Pc.sigma_r     * z(1:K);
    thm = atan2(Y(ks), X(ks))   + Pc.sigma_theta * z(K+1:2*K);
    ts  = (0:K-1)' * Pc.Ts_radar;
    valid = ~(ts >= cfg.t_bo0 - 1e-9 & ts < cfg.t_bo0 + cfg.t_bo - 1e-9);
    hold = zeros(K,1);                                   % index of last valid sample
    last = 1;
    for k = 1:K
        if valid(k), last = k; end
        hold(k) = last;
    end
end

% ---- evaluate at time t -------------------------------------------------
if t < -1e-12 || t > Tgrid
    error('target_motion_generator:timeRange', 't = %g outside [0, %g].', t, Tgrid);
end
k0 = floor(t/Pc.Ts_radar + 1e-9);               % latest sample index (0-based)
is_sample  = abs(t - k0*Pc.Ts_radar) < 1e-9;
meas_valid = is_sample && valid(k0+1);
kh         = hold(k0+1);
r_meas     = rm(kh);
theta_meas = thm(kh);

if nargout >= 4
    f  = t/1e-3;  i0 = min(floor(f + 1e-9) + 1, numel(tg)-1);  fr = f - (i0-1);
    li = @(a) (1-fr)*a(i0) + fr*a(i0+1);
    truth.x = li(X);  truth.y = li(Y);
    truth.vx = li(VX); truth.vy = li(VY);
    truth.ax = li(AX); truth.ay = li(AY);
    truth.r = hypot(truth.x, truth.y);
    truth.theta = atan2(truth.y, truth.x);
end
end

% =========================================================================
function z = gauss_lcg(n, seed)
%GAUSS_LCG  n standard-normal samples from Park-Miller (16807) + Box-Muller.
%   Uses only integer-valued double arithmetic < 2^53, hence identical in
%   MATLAB and Octave.
m = 2147483647;  a = 16807;
s = mod(abs(round(seed)), m-1) + 1;
for k = 1:10, s = mod(a*s, m); end              % burn-in
nn = n + mod(n,2);
u = zeros(nn,1);
for k = 1:nn
    s = mod(a*s, m);
    u(k) = s/m;
end
u1 = u(1:2:end);  u2 = u(2:2:end);
rad = sqrt(-2*log(u1));
zz  = [rad.*cos(2*pi*u2); rad.*sin(2*pi*u2)];
z   = zz(1:n);
end
